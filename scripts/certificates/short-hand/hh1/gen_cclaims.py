out = []
for nm in sys.argv[2:]:
    le, kw, doc = SPEC[nm]
    e = C.claims[nm]
    if nm in ('A0', 'X1a'):
        e = e.subs(C.b, C.x + sp.Rational(10, 13) * (C.a - 1))
    t = time.time()
    c = Claim3(nm, e, has_b=e.has(C.b), has_u=e.has(C.u), **kw)
    assert c.certify(), nm
    out.append(emit_claim3(c, f"hh1c_claim_{nm}", le, needed(le), doc))
    print(nm, 'P', len(c.P), 'items', len(c.T1) + len(c.T2) + len(c.T3), '%.1fs' % (time.time() - t), file=sys.stderr)
