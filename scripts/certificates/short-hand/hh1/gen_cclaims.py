import re
DEFS = {}
def load_defs():
    import glob
    for f in glob.glob(os.path.join(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', '..', 'SmoothedOctagon', 'Exclusion', 'Mixed', 'ShortHand', 'Heavy'), 'S1*.lean')):
        txt = open(f).read()
        for m in re.finditer(r"noncomputable def (hh1\w+)[^:]*:[^=]*:=(.*?)(?=\n\n|\n/--|\nend )", txt, re.S):
            DEFS[m.group(1)] = m.group(2)
    DEFS['hsDg'] = ''
load_defs()
def needed(le):
    seen = []
    todo = re.findall(r"hh1\w+|hsDg", le)
    while todo:
        n = todo.pop()
        if n in seen or n not in DEFS:
            continue
        seen.append(n)
        todo += re.findall(r"hh1\w+|hsDg", DEFS[n])
    return [n for n in UNF if n in seen]
