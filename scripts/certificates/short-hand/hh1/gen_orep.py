import sys, re, pickle, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sympy as sp
x, u = sp.symbols('x u', positive=True)
r, C = sp.symbols('r C', positive=True)
coef, Q = pickle.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'rrep.pkl'), 'rb'))
def lf(e):
    s_ = sp.sstr(e)
    return re.sub(r"\*\*(\d+)", r" ^ (\1 : ℕ)", s_)
def frac(e):
    n, d = sp.fraction(sp.factor(e))
    return f"(({lf(sp.expand(n))}) / ({lf(d)}))"
names = ['hh1oP0', 'hh1oP1', 'hh1oP2', 'hh1oP3', 'hh1oP4']
defs = []
for k, ck in enumerate(coef):
    defs.append(f"/-- Coefficient of `r^{k}` in the reciprocal-shape form of `F₁ + cℓ`. -/\nnoncomputable def {names[k]} (x C u : ℝ) : ℝ :=\n  {frac(ck)}")
defs.append(f"/-- The residue `Q` of the reciprocal-shape form. -/\nnoncomputable def hh1oQ (x C u : ℝ) : ℝ :=\n  {frac(Q)}")
thm = """set_option maxRecDepth 40000 in
set_option maxHeartbeats 4000000 in
/-- **The reciprocal-shape form of the outer `F₁`** (`SHORT_OUTER_LARGE_SHAPE_REDUCTION` (A14)):
with `r = 1/α`, `β = x + C(α - 1)`, `Z = (1 + C) + (x - C)r = (α + β)/α`,
`F₁ = P₀ + P₁r + P₂r² + P₃r³ + P₄r⁴ + Q/Z - (7/96)ℓ(2Z/7)`. -/
theorem hh1o_F1_rep {x C u a b : ℝ} (hx : 1 < x) (ha : 0 < a) (hC : 0 ≤ C) (hCx : C < x)
    (hb : b = x + C * (a - 1)) :
    hh1oF1 x a b u =
      hh1oP0 x C u + hh1oP1 x C u * (1 / a) + hh1oP2 x C u * (1 / a) ^ 2 + hh1oP3 x C u * (1 / a) ^ 3 +
        hh1oP4 x C u * (1 / a) ^ 4 + hh1oQ x C u * (a / (a + b)) - 7 / 96 * hh1ell (hh1oy a b) := by
  have hab : 0 < a + b := by rw [hb]; nlinarith
  have hS : (1 : ℝ) + x ≠ 0 := by linarith
  have he : x - C ≠ 0 := by linarith
  have he' : -C + x ≠ 0 := by linarith
  have hS' : x + 1 ≠ 0 := by linarith
  have ha0 : a ≠ 0 := ha.ne'
  have hab0 : a + b ≠ 0 := hab.ne'
  have hK : 6 * a ^ 2 + 1 ≠ 0 := by positivity
  simp only [hh1oF1, hh1oF0, hh1oR2]
  simp only [hh1oT, hh1ow, hh1oEL, hh1oG, hh1oL, hh1od, hh1ov, hh1oE, hh1oK, hsDg, hh1oP0, hh1oP1,
    hh1oP2, hh1oP3, hh1oP4, hh1oQ]
  field_simp
  subst hb
  ring"""
hdr = """module

public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S1ODefs

/-!
# Gate S1, outer face: the reciprocal-shape form of `F₁`

At fixed `x`, slope `C` and norm `u`, the outer test `F₁(x, 1/r, x + C(1/r - 1), u)` is a quartic in
`r` plus `Q/Z - (7/96)ℓ(2Z/7)`, `Z = (1 + C) + (x - C)r` (`SHORT_OUTER_LARGE_SHAPE_REDUCTION` §3,
`SHORT_OUTER_RECIPROCAL_LOW_SHAPE` (6)). Generated by `scripts/certificates/short-hand/gen_orep.py`.
-/

@[expose] public section

namespace SmoothedOctagon

"""
open(sys.argv[1], 'w').write(hdr + "\n\n".join(defs) + "\n\n" + thm + "\n\nend SmoothedOctagon\n")
