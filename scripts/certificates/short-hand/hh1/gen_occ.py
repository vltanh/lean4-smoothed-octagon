"""Outer reciprocal-shape curvature claims cc2, cc3, cc4 on x-pieces."""
import sys, pickle, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sympy as sp
from fractions import Fraction as Fr
from claimg import ClaimG
from emitg import emit_claimg
HERE = os.path.dirname(os.path.abspath(__file__))
x, u = sp.symbols('x u', positive=True)
r, C = sp.symbols('r C', positive=True)
coef, Q = pickle.load(open(os.path.join(HERE, 'rrep.pkl'), 'rb'))
P2, P3, P4 = coef[2], coef[3], coef[4]
c = sp.Rational(7, 96)
e = x - C; dd = 1 + C
Cm = lambda t: Fr(8) * t / (9 * t + 8)
Cp = lambda t: t * (7 * t + 1) / (4 * t * t + 11 * t + 1)
Vb = lambda t: Fr(3, 4) + 2 * (t - 1) ** 2 / ((t + 1) * (35 * t + 13))
EX = {
    'cc2': (-(4 * P4 / x + P3), "-(4 * hh1oP4 x C u / x + hh1oP3 x C u)", ['hh1oP4', 'hh1oP3']),
    'cc3': (-Q, "-hh1oQ x C u", ['hh1oQ']),
    'cc4': (-(12 * P4 / x ** 2 + 6 * P3 / x + 2 * P2 + c * (e * x / (dd * x + e)) ** 2),
            "-(12 * hh1oP4 x C u / x ^ (2 : ℕ) + 6 * hh1oP3 x C u / x + 2 * hh1oP2 x C u + "
            "7 / 96 * ((x - C) * x / ((1 + C) * x + (x - C))) ^ (2 : ℕ))", ['hh1oP4', 'hh1oP3', 'hh1oP2']),
}
PIECES = [(Fr(6, 5), Fr(13, 10)), (Fr(13, 10), Fr(3, 2)), (Fr(3, 2), Fr(7, 4)), (Fr(7, 4), Fr(2))]
POS = ["have he : x - C ≠ 0 := by linarith only [hx0, hv01]",
       "have he' : -C + x ≠ 0 := by linarith only [hx0, hv01]",
       "have hS : x + 1 ≠ 0 := by linarith only [hx0]",
       "have hS' : 1 + x ≠ 0 := by linarith only [hx0]",
       "have hx' : x ≠ 0 := by linarith only [hx0]",
       "have hZ : (1 + C) * x + (x - C) ≠ 0 := by nlinarith only [hx0, hv00, hv01]",
       "have hZ2 : -C + 2 * x + C * x ≠ 0 := by nlinarith only [hx0, hv00, hv01]"]


def claims(pieces=PIECES):
    out = []
    for k, (x0, x1) in enumerate(pieces):
        for nm, (E_, le, unf) in EX.items():
            clo, chi = Cm(x0), Cp(x1)
            cl = ClaimG(E_, x, x0, 1, x1 - x0, [(C, clo, (chi - clo, 0)), (u, Fr(3, 4), (Vb(x1) - Fr(3, 4), 0))])
            assert cl.certify(), (nm, x0, x1)
            out.append((f"hh1o_claim_{nm}_{k}", cl, le, unf, x0, x1))
    return out


HDR = """module

public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S1ORep
public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S1Tw

/-!
# Gate S1, outer face: reciprocal-shape curvature signs, piece {k}

On `{x0} ≤ x ≤ {x1}`, `C₋({x0}) ≤ C ≤ C₊({x1})`, `3/4 ≤ u ≤ V̄({x1})`: the signs
`4P₄/x + P₃ ≤ 0`, `Q ≤ 0` and `12P₄/x² + 6P₃/x + 2P₂ + c(ex/(dx + e))² ≤ 0` (`e = x - C`,
`d = 1 + C`) bounding the reciprocal-shape curvature (`SHORT_OUTER_RECIPROCAL_LOW_SHAPE` §3).
Generated by `scripts/certificates/short-hand/gen_occ.py`: cleared numerator, termwise bounds in
`C` and `u`, Bernstein coefficients in `x`.
-/

@[expose] public section

namespace SmoothedOctagon

"""

if __name__ == '__main__':
    outdir = sys.argv[1]
    sel = [int(s) for s in sys.argv[2:]] if len(sys.argv) > 2 else range(len(PIECES))
    for k in sel:
        x0, x1 = PIECES[k]
        body = []
        for nm, (E_, le, unf) in EX.items():
            clo, chi = Cm(x0), Cp(x1)
            cl = ClaimG(E_, x, x0, 1, x1 - x0, [(C, clo, (chi - clo, 0)), (u, Fr(3, 4), (Vb(x1) - Fr(3, 4), 0))])
            assert cl.certify(), (nm, x0, x1)
            print(nm, k, 'P', len(cl.P), 'H', len(cl.H))
            body.append(emit_claimg(cl, f"hh1o_claim_{nm}_{k}", le, unf,
                                    f"Outer curvature sign `{nm}` on `[{x0}, {x1}]` (generated).",
                                    ['C', 'u'], pos_hyps=POS))
        txt = HDR.replace('{k}', str(k)).replace('{x0}', str(x0)).replace('{x1}', str(x1))
        open(os.path.join(outdir, f"S1OCurv{k}.lean"), 'w').write(txt + "\n\n".join(body) + "\n\nend SmoothedOctagon\n")
