"""Writes Heavy/S0Faces.lean: the three heavy S0 leaves with their exact skeleton statements.

usage (from the repository root): python3 scripts/certificates/short-hand/s0/mkfaces.py
"""
S0='SmoothedOctagon/Exclusion/Mixed/ShortHand/S0.lean'
OUT='SmoothedOctagon/Exclusion/Mixed/ShortHand/Heavy/S0Faces.lean'
s=open(S0).read()
def stmt(name):
    i=s.index(f"theorem {name} ")
    j=s.index(":= by\n  sorry",i)
    return s[i:j]
proofs={
 'hs0_central_tau_two':"  (fun _ => hh0C2_neg hx hal hal' hxb hb) hx9",
 'hs0_central_duration':"  (fun _ => ⟨hh0CT_neg hx hal hal' hxb hb, hh0C8_neg hx hal hal' hxb hb⟩) hx9",
 'hs0_outer_tests':"  (fun _ => ⟨hh0OT_neg hx hal hax hb hb', hh0O8_neg hx hal hax hb hb', hh0O2_neg hx hal hax hb hb'⟩) hx9",
}
docs={
 'hs0_central_tau_two':"""/-- **The central face, `τ = 2` test** (`CENTRAL_TAU_TWO_SIGN` (3); inventory HS-S01 B7): the
statement of `hs0_central_tau_two`. Route: nested Bernstein certificate `hh0C2_neg` (the bound
`x ≤ 9` is not needed). -/""",
 'hs0_central_duration':"""/-- **The central face, `τ = T` and `τ = 8T/9` tests** (`CENTRAL_DURATION_FACES` (5); inventory
HS-S01 B8): the statement of `hs0_central_duration`. Route: nested Bernstein certificates
`hh0CT_neg`, `hh0C8_neg` (no β-convexity step; the bound `x ≤ 9` is not needed). -/""",
 'hs0_outer_tests':"""/-- **The outer face, three tests** (`OUTER_SCALE_LARGE_RATIO_SIGN` (7); inventory HS-S01 B9): the
statement of `hs0_outer_tests`. Route: nested Bernstein certificates `hh0OT_neg`, `hh0O8_neg`,
`hh0O2_neg` on the larger strip `x ≤ β` (the bound `x ≤ 9` is not needed). -/""",
}
out="""module

public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S0C2
public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S0CT
public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S0C8
public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S0OT
public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S0O8
public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S0O2

/-!
# Hand proof of the smaller-short case, gate S0: the heavy face signs

The three heavy leaves of gate S0 (`hs0_central_tau_two`, `hs0_central_duration`,
`hs0_outer_tests`), proved with their exact statements as `*_proof`.

Each of the six face tests is `hsF = -N/Den` with an explicit polynomial `N` in `(x, α, β)` and
`Den > 0`; `N > 0` is certified by nested Bernstein expansions (in `b = β - x` on the β-strip, then
in `α` on its interval, ending in polynomials in `X = x - 12/5` with nonnegative coefficients).
The certificates are in `Heavy/S0{C2,CT,C8,OT,O8,O2}` (the outer ones with coefficient modules
`Heavy/S0O*Cert`), generated by `scripts/certificates/short-hand/s0/gens0.py`.

Route: the notes' β-convexity (central faces) and their coefficient tables (`CENTRAL_TAU_TWO_SIGN`
(15)-(17), `CENTRAL_DURATION_FACES` (25)-(30), `OUTER_SCALE_LARGE_RATIO_SIGN` (17)-(19)) are replaced by
the nested certificates; the hypothesis `x ≤ 9` is not used, and the outer signs hold on the larger
strip `x ≤ β` (the lower order bound only gives `β ≥ x`).

## Main API

* `hs0_central_tau_two_proof`, `hs0_central_duration_proof`, `hs0_outer_tests_proof`.
-/

@[expose] public section

namespace SmoothedOctagon

"""
for name in ['hs0_central_tau_two','hs0_central_duration','hs0_outer_tests']:
    st=stmt(name).replace(f"theorem {name} ",f"theorem {name}_proof ",1)
    out+=docs[name]+"\n"+st+":=\n"+proofs[name]+"\n\n"
out+="end SmoothedOctagon\n"
open(OUT,'w').write(out)
