"""Generator of the four auxiliary 2D certificates of the beta-step (S4Beta*):
k_Phi >= 1/15, k_I >= 1/15, k_II >= 1/15, L_u >= -13/20 on x in [2, 13/6], al in [1, 22/19],
at u in {757/1000, 19/25} (all four are affine in u)."""
import sympy as sp, re, sys
from fractions import Fraction as Fr
from math import comb
sys.path.insert(0, '.')
from leanfmt import lnum, pw, upoly, fullpoly, slit
from s6gen import shift, HEAD

xs, al, u = sp.symbols('x al u')
def hsDg(x, b, a): return a**2 + 2*a*b + 1 + 2*x - 2*b*x
def hh46S4P(x, uu): return (1 + x)**3*(uu - 1) + 3*(1 + x) - 1
def hh46S4Wc(x, b, a, uu):
    return ((1 + x)**2*((1 + x)**2 - (1 + x) + 1) + hsDg(x, b, a)**2*uu - hsDg(x, b, a)*hh46S4P(x, uu))/(x*(x + 2) + a**2)**2

DEFS = {
 'kPhi': ("4 * (x - al) * (u * (x * (x + 2) + al ^ 2) - 2 * hsDg x x al * u + hh46S4P x u) / "
          "(x * (x + 2) + al ^ 2) ^ 2 - (1 - u) / al + x / ((al + x) * (al + 20 / 19 * x))"),
 'tE': ("2 * ((x * (x + 2) + al ^ 2) / (al * (al + x)) - 2) * (x - al) * (2 * hsDg x x al * u - hh46S4P x u) / "
        "(x * (x + 2) + al ^ 2) ^ 2"),
 'Lu': ("(4 * (1 + x) ^ 2 * ((1 + x) ^ 2 - (1 + x) + 1) - 2 * hh46S4P x u * (1 + x) ^ 3) / (16 * x ^ 2 * (x + 2) ^ 2) - "
        "(2 * hsDg x (20 / 19 * x) al * (hsDg x (20 / 19 * x) al - (1 + x) ^ 3) / (x * (x + 2) + al ^ 2) ^ 2 + "
        "(al + 20 / 19 * x) / al - (2 * hsDg x (20 / 19 * x) al - (1 + x) ^ 3) / (x * (x + 2) + al ^ 2)) / 7"),
}
DEFS['kI'] = "hh46S4kPhi x al u - (x * (x + 2) + al ^ 2) * (hh46S4Wc x x al u - 3 / 4) / (al * (al + x) ^ 2) - hh46S4tE x al u"
DEFS['kII'] = "hh46S4kPhi x al u - hh46S4tE x al u"

def to_sympy(s, env):
    t = s.replace('^', '**')
    # function applications f a b c -> f(a, b, c): handle the specific names
    for f, n in (('hsDg', 3), ('hh46S4P', 2), ('hh46S4Wc', 4), ('hh46S4kPhi', 3), ('hh46S4tE', 3)):
        pat = f + r" ((?:\([^()]*(?:\([^()]*\))*[^()]*\)|[a-z0-9_]+)(?: (?:\([^()]*(?:\([^()]*\))*[^()]*\)|[a-z0-9_]+)){%d})" % (n - 1)
        def rep(m, f=f):
            args = re.findall(r"\([^()]*(?:\([^()]*\))*[^()]*\)|[a-z0-9_]+", m.group(1))
            return f + "(" + ", ".join(args) + ")"
        t = re.sub(pat, rep, t)
    return sp.sympify(t, locals=env)

def sym_defs():
    env = dict(x=xs, al=al, u=u, hsDg=hsDg, hh46S4P=hh46S4P, hh46S4Wc=hh46S4Wc)
    out = {}
    out['kPhi'] = to_sympy(DEFS['kPhi'], env)
    out['tE'] = to_sympy(DEFS['tE'], env)
    out['Lu'] = to_sympy(DEFS['Lu'], env)
    env2 = dict(env, hh46S4kPhi=lambda a, b, c: out['kPhi'].subs({xs: a, al: b, u: c}, simultaneous=True),
                hh46S4tE=lambda a, b, c: out['tE'].subs({xs: a, al: b, u: c}, simultaneous=True))
    out['kI'] = to_sympy(DEFS['kI'], env2)
    out['kII'] = to_sympy(DEFS['kII'], env2)
    return out

CLAIMS = [('kPhi', Fr(1, 15)), ('kI', Fr(1, 15)), ('kII', Fr(1, 15)), ('Lu', Fr(-13, 20))]
UV = [Fr(757, 1000), Fr(19, 25)]
DENS = {
 'kPhi': "(x * (x + 2) + al ^ 2) ^ 2 * al * (al + x) * (al + 20 / 19 * x)",
 'kI': "(x * (x + 2) + al ^ 2) ^ 2 * al ^ 2 * (al + x) ^ 2 * (al + 20 / 19 * x)",
 'kII': "(x * (x + 2) + al ^ 2) ^ 2 * al ^ 2 * (al + x) * (al + 20 / 19 * x)",
 'Lu': "x ^ 2 * (x + 2) ^ 2 * (x * (x + 2) + al ^ 2) ^ 2 * al",
}

def cert(name, kap, u0):
    S = sym_defs()
    f = S[name].subs(u, sp.Rational(u0.numerator, u0.denominator))
    den = to_sympy(DENS[name], dict(x=xs, al=al))
    N = sp.cancel((f - sp.Rational(kap.numerator, kap.denominator)) * den)
    n, d = sp.fraction(N)
    assert d.is_number, (name, d)
    P = sp.Poly(sp.expand(N), xs, al)
    D = {k: Fr(int(sp.numer(c)), int(sp.denom(c))) for k, c in P.as_dict().items()}
    # shift al -> 1 + a, x -> 2 + t
    a = sp.Symbol('a'); t = sp.Symbol('t')
    Q = sp.Poly(sp.expand(P.as_expr().subs({al: 1 + a})), xs, a)
    Dq = {k: Fr(int(sp.numer(c)), int(sp.denom(c))) for k, c in Q.as_dict().items()}
    nx = max(i for i, j in Dq); na = max(j for i, j in Dq)
    C = [[Dq.get((i, j), Fr(0)) for i in range(nx + 1)] for j in range(na + 1)]
    return C, nx, na

