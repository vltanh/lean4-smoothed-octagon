                             "`L_u ≥ -13/20`\n(all four are affine in `u`; at each end of the `u`-interval, the cleared "
                             "numerator is positive by\na small Bernstein certificate; generated by "
                             "`scripts/certificates/short-hand/hh46/s4claims.py`).\n\n"
                             "## Main API\n\n`hh46S4kPhi`, `hh46S4tE`, `hh46S4kI`, `hh46S4kII`, `hh46S4Lu`, "
