"""Generator of the S4 face certificates (`hs4_floor_box`).

Faces: A = {eta = 13/5}: (x, delta) in [2, 13/6] x [0, 1/19], alpha = 1 + 13 delta/5, beta = x(1 + delta);
       B = {delta = 1/19}: (x, alpha) in [2, 13/6] x [108/95, 22/19], beta = 20x/19.
On each face, F in {Phi, Psi} with u = ubar and log replaced by the surrogate
L0 + h - h^2/2 + h^3/3, h = k y - 1 (k = 1/y0): the structured numerator `hh46S4N{F}` (high-level
atoms) evaluated on the face is expanded as sum_j C_j(x) w^j (w = delta, resp. alpha - 108/95) and
proved positive by nested Bernstein (w outer, x - 2 inner).
"""
import sympy as sp, sys
from fractions import Fraction as Fr
from math import comb
from leanfmt import lnum, pw, upoly, fullpoly, slit
sys.path.insert(0, '.')
from s4atomsN import NF, X, AL, A, Sg, S, U, D, Pn, nu, du, k, L0
from s6gen import shift, HEAD

R_ = sp.Rational
xs, vs = sp.symbols('x v')

def log_ub(y0):
    w = (1 - y0) / (1 + y0)
    return -2 * (w + w**3 / 3 + w**5 / 5)

FACES = {
    'A': dict(y0=R_(2524608, 3353029), al=1 + R_(13, 5) * vs, be=xs * (1 + vs), w0=R_(0), g=R_(1, 19),
              lal="(1 + 13 / 5 * v)", lbe="(x * (1 + v))", wname="v"),
    'B': dict(y0=R_(103488, 134749), al=vs, be=xs * R_(20, 19), w0=R_(108, 95), g=R_(2, 95),
              lal="v", lbe="(20 / 19 * x)", wname="(v - 108 / 95)"),
}

def ubar_nd(be):
    """nu, du polynomials (in x, v) with ubar = nu/du."""
    ub = R_(3, 4) + (2 * (xs - 1)**3 / ((xs + 1) * (35 * xs + 13)) + (be - xs)**3 / (48 * xs**2)) / (be - 1)
    n, d = sp.fraction(sp.cancel(sp.together(ub)))
    return sp.expand(n), sp.expand(d)

def face_poly(face, which):
    f = FACES[face]
    y0 = f['y0']; kk = 1 / y0; LL = log_ub(y0)
    al = f['al']; be = f['be']
    n_, d_ = ubar_nd(be)
    S_ = 1 + xs
    sub = {X: xs, AL: al, A: al + be, Sg: xs * (xs + 2) + al**2, S: S_, U: S_**2 - S_ + 1,
           D: al**2 + 2 * al * be + 1 + 2 * xs - 2 * be * xs,
           Pn: S_**3 * (n_ - d_) + (3 * S_ - 1) * d_, nu: n_, du: d_, k: kk, L0: LL}
    N, M = NF(which)
    P = sp.expand(N.subs(sub))
    w = sp.Symbol('w')
    P = sp.Poly(sp.expand(P.subs(vs, w + f['w0'])), xs, w)
    Dd = {kk_: Fr(int(sp.numer(c)), int(sp.denom(c))) for kk_, c in P.as_dict().items()}
    nx = max(i for i, j in Dd); nw = max(j for i, j in Dd)
    C = [[Dd.get((i, j), Fr(0)) for i in range(nx + 1)] for j in range(nw + 1)]
    return C, nx, nw, n_, d_, kk, LL

def lexpr(e):
    """sympy polynomial expression in x, v -> Lean string (typed powers)."""
    P = sp.Poly(sp.expand(e), xs, vs)
    parts = []
    for (i, j), c in sorted(P.as_dict().items()):
        c = Fr(int(sp.numer(c)), int(sp.denom(c)))
        m = " * ".join(t for t in (pw('x', i), pw('v', j)) if t)
        a = abs(c)
        t = lnum(a) if not m else (m if a == 1 else f"{lnum(a)} * {m}")
        parts.append(("- " if c < 0 else "+ ") + t)
    s = " ".join(parts)
    return "(" + (s[2:] if s.startswith("+ ") else "-" + s[2:]) + ")"

def emit_id(face, which, C, nx, nw, n_, d_, kk, LL):
    f = FACES[face]; tag = f"{which}{face}"
    al = f['lal']; be = f['lbe']; wn = f['wname']
    S_ = "(1 + x)"
    args = (f"x {al} ({al} + {be}) (x * (x + 2) + {al} ^ 2) {S_} ({S_} ^ 2 - {S_} + 1) "
            f"(hsDg x {be} {al})\n      ({S_} ^ 3 * ({lexpr(n_)} - {lexpr(d_)}) + (3 * {S_} - 1) * {lexpr(d_)})\n"
            f"      {lexpr(n_)}\n      {lexpr(d_)}\n      {slit(kk)} {slit(LL)}")
    out = [HEAD.format(imports="public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S4Surr",
                       title=f"Heavy leaf `hs4_floor_box`: the expansion of `{which}` on face {face}",
                       body=(f"The surrogate numerator `hh46S4N{which}` on face {face} as `∑ⱼ Cⱼ(x) wʲ`, `w = {wn}` "
                             "(generated by\n`scripts/certificates/short-hand/hh46/s4gen.py`; one `ring` identity).\n\n"
                             f"## Main API\n\n`hh46S4C{tag}_j`, `hh46_s4_id{tag}`."))]
    for j in range(nw + 1):
        out.append(f"/-- Coefficient of `w^{j}`. -/\nnoncomputable def hh46S4C{tag}_{j} (x : ℝ) : ℝ :=\n  {upoly(C[j], 'x')}\n")
    rhs = " + ".join(f"hh46S4C{tag}_{j} x" + ("" if j == 0 else f" * {pw(wn, j)}") for j in range(nw + 1))
    unf = " ".join(f"hh46S4C{tag}_{j}" for j in range(nw + 1))
    out.append(f"""/-- The expansion of the surrogate numerator of `{which}` on face {face}. -/
theorem hh46_s4_id{tag} (x v : ℝ) :
    hh46S4N{which} {args} =
      {rhs} := by
  unfold hh46S4N{which} hsDg {unf}
  ring
""")
    out.append("end SmoothedOctagon\n")
    return "\n".join(out)

def emit_pos(face, which, C, nx, nw):
    f = FACES[face]; tag = f"{which}{face}"
    g = Fr(f['g'].p, f['g'].q); gx = Fr(1, 6)
    wn = f['wname']; w0 = Fr(f['w0'].p, f['w0'].q)
    out = [HEAD.format(imports=("public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S4Bern\n"
                                f"public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S4Id{tag}"),
                       title=f"Heavy leaf `hs4_floor_box`: Bernstein positivity of `{which}` on face {face}",
                       body=(f"`∑ⱼ Cⱼ(x) wʲ > 0` for `x ∈ [2, 13/6]`, `w ∈ [0, {g}]`: Bernstein in `w` (degree {nw}) with "
                             f"polynomial coefficients\n`E_k(x - 2)`, each positive by Bernstein in `x - 2` (degree {nx}); "
                             "all coefficients are positive without\nsubdivision (generated by "
                             "`scripts/certificates/short-hand/hh46/s4gen.py`).\n\n"
                             f"## Main API\n\n`hh46S4E{tag}_k`, `hh46_s4_pos{tag}`."))]
    for kk in range(nw + 1):
        Ek = shift([sum(comb(nw - j, kk - j) * C[j][i] * g**j for j in range(kk + 1)) for i in range(nx + 1)], Fr(2))
        bs = [sum(comb(nx - i, m - i) * Ek[i] * gx**i for i in range(m + 1)) for m in range(nx + 1)]
        assert all(b_ > 0 for b_ in bs), (face, which, kk)
        out.append(f"/-- The `w`-Bernstein coefficient `E_{kk}` (in `t = x - 2`). -/\n"
                   f"noncomputable def hh46S4E{tag}_{kk} (t : ℝ) : ℝ :=\n  {fullpoly(Ek, 't')}\n")
        nb = " ".join("(by norm_num)" for _ in range(nx + 1))
        out.append(f"""theorem hh46_s4_E{tag}_pos_{kk} {{t : ℝ}} (h0 : 0 ≤ t) (h1 : t ≤ 1 / 6) : 0 < hh46S4E{tag}_{kk} t := by
  unfold hh46S4E{tag}_{kk}
  exact hh46Bern0g{nx} h0 h1 (by norm_num)
    {nb}
""")
    lhs = " + ".join(f"hh46S4C{tag}_{j} x" + ("" if j == 0 else f" * {pw(wn, j)}") for j in range(nw + 1))
    steps = []
    for kk in range(nw + 1):
        comb_s = " + ".join(" * ".join(z for z in [None if comb(nw - j, kk - j) == 1 else str(comb(nw - j, kk - j)),
                                                   f"hh46S4C{tag}_{j} x", pw(f"({lnum(g)})", j)] if z)
                            for j in range(kk + 1))
        unfk = " ".join(f"hh46S4C{tag}_{j}" for j in range(kk + 1))
        steps.append(f"  · have e : {comb_s} = hh46S4E{tag}_{kk} (x - 2) := by\n      unfold hh46S4E{tag}_{kk} {unfk}; ring\n"
                     f"    rw [e]; exact hh46_s4_E{tag}_pos_{kk} (by linarith) (by linarith)")
    lo = "0" if w0 == 0 else lnum(w0)
    hi = lnum(w0 + g)
    out.append(f"""/-- **Positivity of the expansion** of `{which}` on face {face}. -/
theorem hh46_s4_pos{tag} {{x v : ℝ}} (hx0 : 2 ≤ x) (hx1 : x ≤ 13 / 6) (hv0 : {lo} ≤ v) (hv1 : v ≤ {hi}) :
    0 < {lhs} := by
  refine hh46Bern0g{nw} (y := {wn}) (g := {lnum(g)}) (by linarith) (by linarith) (by norm_num) {' '.join('?_' for _ in range(nw + 1))}
""" + "\n".join(steps) + "\n")
    out.append("end SmoothedOctagon\n")
    return "\n".join(out)

if __name__ == "__main__":
    outdir = sys.argv[1]
    which_faces = sys.argv[2:] if len(sys.argv) > 2 else ['A', 'B']
    for face in which_faces:
        for which in ('Phi', 'Psi'):
            C, nx, nw, n_, d_, kk, LL = face_poly(face, which)
            print(face, which, nx, nw, sum(1 for j in range(nw + 1) for i in range(nx + 1) if C[j][i] != 0), file=sys.stderr)
            tag = f"{which}{face}"
            open(f"{outdir}/S4Id{tag}.lean", "w").write(emit_id(face, which, C, nx, nw, n_, d_, kk, LL))
            open(f"{outdir}/S4Pos{tag}.lean", "w").write(emit_pos(face, which, C, nx, nw))
