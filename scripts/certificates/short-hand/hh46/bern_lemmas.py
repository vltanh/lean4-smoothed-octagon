"""Generic Bernstein positivity lemmas with abstract coefficients (Lean emitter).

* `hh46BernPos{n}`: `0 < sum_k c_k a^k b^(n-k)` when `a, b >= 0`, `a + b > 0`, all `c_k > 0`;
* `hh46Bern0g{n}`: `0 < sum_i c_i y^i` on `[0, g]` when every Bernstein coefficient
  `sum_{i <= k} C(n - i, k - i) c_i g^i` is positive (identity
  `g^n sum_i c_i y^i = sum_k b_k y^k (g - y)^(n - k)`, checked by `ring`).
"""
from math import comb

def pw(v, k):
    if k == 0: return None
    if k == 1: return v
    return f"{v} ^ ({k} : ℕ)"

def mul(*fs):
    fs = [f for f in fs if f is not None]
    return " * ".join(fs) if fs else "1"

def bpos(n):
    cs = " ".join(f"c{k}" for k in range(n + 1))
    hyps = " ".join(f"(h{k} : 0 < c{k})" for k in range(n + 1))
    terms = [mul(f"c{k}", pw("a", k), pw("b", n - k)) for k in range(n + 1)]
    full = " + ".join(terms)
    rest_hi = " + ".join(terms[:-1])
    rest_lo = " + ".join(terms[1:])
    return f"""/-- A Bernstein form of degree {n} with positive coefficients is positive. -/
theorem hh46BernPos{n} {{a b : ℝ}} (ha : 0 ≤ a) (hb : 0 ≤ b) (hab : 0 < a + b) {{{cs} : ℝ}}
    {hyps} :
    0 < {full} := by
  rcases lt_or_ge 0 a with h | h
  · have h' : 0 < {terms[-1]} := by positivity
    have h'' : 0 ≤ {rest_hi} := by positivity
    linarith
  · have hb' : 0 < b := by linarith
    have h' : 0 < {terms[0]} := by positivity
    have h'' : 0 ≤ {rest_lo} := by positivity
    linarith
"""

def bcoef(n, k):
    """Lean string of sum_{i<=k} C(n-i,k-i) c_i g^i."""
    parts = []
    for i in range(k + 1):
        b = comb(n - i, k - i)
        parts.append(mul(None if b == 1 else str(b), f"c{i}", pw("g", i)))
    return " + ".join(parts)

def b0g(n):
    cs = " ".join(f"c{k}" for k in range(n + 1))
    hyps = "\n".join(f"    (hb{k} : 0 < {bcoef(n, k)})" for k in range(n + 1))
    poly = " + ".join(mul(f"c{i}", pw("y", i)) for i in range(n + 1))
    rhs = " + ".join(mul(f"({bcoef(n, k)})", pw("y", k), pw("(g - y)", n - k)) for k in range(n + 1))
    hb = " ".join(f"hb{k}" for k in range(n + 1))
    return f"""/-- Bernstein positivity of degree {n} on `[0, g]`, with abstract coefficients. -/
theorem hh46Bern0g{n} {{g y {cs} : ℝ}} (h0 : 0 ≤ y) (h1 : y ≤ g) (hg : 0 < g)
{hyps} :
    0 < {poly} := by
  have hpos := hh46BernPos{n} (a := y) (b := g - y) h0 (by linarith) (by linarith) {hb}
  have e : g ^ ({n} : ℕ) * ({poly}) = {rhs} := by ring
  rw [← e] at hpos
  exact pos_of_mul_pos_right hpos (by positivity)
"""

def module(degrees, name, doc):
    out = [f"""module

public import Mathlib.Basic.Real.Basic
public import Mathlib.Tactic.Ring
public import Mathlib.Tactic.Linarith
public import Mathlib.Tactic.Positivity

/-!
# {doc}

Generic Bernstein positivity with abstract coefficients (generated by
`scripts/certificates/short-hand/hh46/bern_lemmas.py`):

* `hh46BernPos{{n}}`: a Bernstein form with positive coefficients is positive;
* `hh46Bern0g{{n}}`: `∑ cᵢ yⁱ > 0` on `[0, g]` when its Bernstein coefficients
  `∑_{{i ≤ k}} C(n - i, k - i) cᵢ gⁱ` are positive (one `ring` identity per degree).

Degrees: {", ".join(map(str, degrees))}.
-/

@[expose] public section

namespace SmoothedOctagon
"""]
    for n in degrees:
        out.append(bpos(n))
    for n in degrees:
        out.append(b0g(n))
    out.append("end SmoothedOctagon\n")
    return "\n".join(out)

if __name__ == "__main__":
    import sys
    degs = [int(a) for a in sys.argv[2:]]
    open(sys.argv[1], "w").write(module(degs, "", "Heavy H-S leaves: generic Bernstein lemmas"))
