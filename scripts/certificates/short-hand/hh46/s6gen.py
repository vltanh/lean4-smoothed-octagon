"""Generator of the S6 endpoint certificate (`hs6_B_endpoint`).

For e in {13/5, 3}: with atoms b = q B, n = q N (T = n/b, q the denominator of e) and nu/du = u_q,
the cleared numerator `hh46S6St R d b n nu du` of `B(u_q; R, T, d) - b*` (denominator
`b^5 K1 K2^2 du fac`, `S6Link`) times an integer M is expanded as sum_j C_j(R) d^j with integer
coefficients (one `ring` identity, `S6Id*`), and positivity on [1/3, 7/19] x [0, 1/19] is proved by
nested Bernstein (`S6Pos*`: d outer, degree 14; y = R - 1/3 inner, degree 24).  All tensor
Bernstein coefficients are positive without subdivision.
"""
import sympy as sp, sys
from fractions import Fraction as Fr
from math import comb
from leanfmt import lnum, pw, upoly, fullpoly

R_ = sp.Rational
Rs, ds, ys = sp.symbols('R d y')
c = R_(161, 54); bstar = R_(792669623, 356040000000)

def Lf(z): return z/162 + 161*z**3/1458 - 161*z**5/7290

def St(R, d, b, n, nu, du):
    K1 = 3 + R**2; K2 = 3*b**2 + n**2
    N1 = K1*du - 4*nu; N2 = K2*du - 4*b**2*nu; NA = K1*b**2 - K2
    NZ = 12*R**2*(1+R)*(1-R) + 2*(1+2*R)*(3-R)*d - 9*(3-R)*(1-R)*d**2
    fac = (3-R)*(1-R)*R**2*(1+R)*(2+11*d)
    return (b**5*K1*K2**2*du*fac*(Lf(R) - bstar)
            + K1*K2**2*du*fac*(n*b**4/162 + 161*n**3*b**2/1458 - 161*n**5/7290)
            - b**5*K2**2*fac*N1*R/2
            - b**4*K1*K2*fac*N2*n/2
            - b**5*K2*R**2*(1+R)*(2+11*d)*NZ*(N1*K2 + N2*K1)/48
            - b**5*K1*du*(3-R)*(1-R)*161*(3-R)*NA**2/432)

def atoms(e):
    q = e.q; p = e.p
    b = 2*q + ((p+q) - (p-q)*Rs)*ds
    n = 2*q*Rs + ((p+q)*Rs - (p-q))*ds
    H = 3*Rs**2 + 10*Rs + 10
    du = 1260*(2+Rs)**3
    nu = 945*(2+Rs)**3 + 84*H*Rs**2 - 42*H*Rs*(1+Rs)*ds + 19*H*(1+Rs)**2*ds**2
    return b, n, nu, du

def coeffs(e):
    """M and C[j][i]: M * St = sum_j (sum_i C[j][i] R^i) d^j with integer C."""
    from math import lcm
    from functools import reduce
    b, n, nu, du = atoms(e)
    W = sp.Poly(sp.expand(St(Rs, ds, b, n, nu, du)), Rs, ds)
    D = {k: Fr(int(sp.numer(v)), int(sp.denom(v))) for k, v in W.as_dict().items()}
    M = reduce(lcm, [v.denominator for v in D.values()])
    ny = max(i for i, j in D); nd = max(j for i, j in D)
    C = [[D.get((i, j), Fr(0)) * M for i in range(ny + 1)] for j in range(nd + 1)]
    return M, C, ny, nd

def shift(cs, a):
    """coefficients of p(y + a) given p's coefficients."""
    from math import comb as cb
    n = len(cs) - 1
    return [sum(cs[i] * cb(i, k) * a**(i - k) for i in range(k, n + 1)) for k in range(n + 1)]

def bern_y(cs, g, n):
    """Bernstein combos sum_{i<=k} C(n-i,k-i) c_i g^i."""
    return [sum(comb(n - i, k - i) * cs[i] * g**i for i in range(k + 1)) for k in range(n + 1)]

def tag(e): return f"{e.p}" if e.q == 1 else f"{e.p}{e.q}"

def lean_atoms(e):
    q = e.q; p = e.p
    b = f"({2*q} + ({p+q} - {p-q} * R) * d)"
    n = f"({2*q} * R + ({p+q} * R - {p-q}) * d)"
    nu = ("(945 * (2 + R) ^ (3 : ℕ) + 84 * (3 * R ^ (2 : ℕ) + 10 * R + 10) * R ^ (2 : ℕ) - "
          "42 * (3 * R ^ (2 : ℕ) + 10 * R + 10) * R * (1 + R) * d + "
          "19 * (3 * R ^ (2 : ℕ) + 10 * R + 10) * (1 + R) ^ (2 : ℕ) * d ^ (2 : ℕ))")
    du = "(1260 * (2 + R) ^ (3 : ℕ))"
    return b, n, nu, du

HEAD = """module

{imports}

/-!
# {title}

{body}
-/

@[expose] public section

namespace SmoothedOctagon
"""

def emit_id(e, M, C, ny, nd):
    t = tag(e)
    b, n, nu, du = lean_atoms(e)
    out = [HEAD.format(imports="public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S6Link",
                       title=f"Heavy leaf `hs6_B_endpoint`: the expansion at `e = {e}`",
                       body=(f"The cleared numerator `hh46S6St` at `e = {e}` (atoms `b = {e.q}·B`, `n = {e.q}·N`, "
                             f"`nu/du = u_q`), times `{M}`, expanded as `∑ⱼ Cⱼ(R) dʲ` with integer coefficients (generated by\n"
                             "`scripts/certificates/short-hand/hh46/s6gen.py`; one `ring` identity).\n\n"
                             f"## Main API\n\n`hh46S6C{t}_j` (`j ≤ {nd}`), `hh46_s6_id{t}`."))]
    for j in range(nd + 1):
        out.append(f"/-- Coefficient of `d^{j}` (a polynomial in `R`) at `e = {e}`. -/\n"
                   f"noncomputable def hh46S6C{t}_{j} (R : ℝ) : ℝ :=\n  {upoly(C[j], 'R')}\n")
    rhs = " + ".join(f"hh46S6C{t}_{j} R" + ("" if j == 0 else f" * {pw('d', j)}") for j in range(nd + 1))
    unf = " ".join(f"hh46S6C{t}_{j}" for j in range(nd + 1))
    out.append(f"""/-- The expansion of the cleared numerator at `e = {e}`. -/
theorem hh46_s6_id{t} (R d : ℝ) :
    {M} * hh46S6St R d {b} {n}
      {nu}
      {du} =
      {rhs} := by
  unfold hh46S6St hs6L hs6bstar {unf}
  ring
""")
    out.append("end SmoothedOctagon\n")
    return "\n".join(out)

def emit_pos(e, M, C, ny, nd, gy=Fr(2, 57), gd=Fr(1, 19)):
    t = tag(e)
    out = [HEAD.format(imports=("public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S6Bern\n"
                                f"public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S6Id{t}"),
                       title=f"Heavy leaf `hs6_B_endpoint`: Bernstein positivity at `e = {e}`",
                       body=(f"`∑ⱼ Cⱼ(R) dʲ > 0` on `[1/3, 7/19] × [0, 1/19]` at `e = {e}`: Bernstein in `d` (degree {nd}) "
                             f"with polynomial\ncoefficients `E_k(R - 1/3)`, each positive by Bernstein in `y = R - 1/3` (degree {ny}); "
                             "all coefficients are positive\nwithout subdivision (generated by "
                             "`scripts/certificates/short-hand/hh46/s6gen.py`).\n\n"
                             f"## Main API\n\n`hh46S6E{t}_k`, `hh46_s6_E{t}_pos_k`, `hh46_s6_pos{t}`."))]
    # outer combos in d: E_k(y) = sum_{j<=k} C(nd-j,k-j) C_j(y) gd^j
    for k in range(nd + 1):
        Ek = shift([sum(comb(nd - j, k - j) * C[j][i] * gd**j for j in range(k + 1)) for i in range(ny + 1)], Fr(1, 3))
        bs = bern_y(Ek, gy, ny)
        assert all(x > 0 for x in bs), (str(e), k)
        out.append(f"/-- The `d`-Bernstein coefficient `E_{k}` at `e = {e}`. -/\n"
                   f"noncomputable def hh46S6E{t}_{k} (y : ℝ) : ℝ :=\n  {fullpoly(Ek, 'y')}\n")
        nb = " ".join("(by norm_num)" for _ in range(ny + 1))
        out.append(f"""theorem hh46_s6_E{t}_pos_{k} {{y : ℝ}} (h0 : 0 ≤ y) (h1 : y ≤ 2 / 57) : 0 < hh46S6E{t}_{k} y := by
  unfold hh46S6E{t}_{k}
  exact hh46Bern0g{ny} h0 h1 (by norm_num)
    {nb}
""")
    lhs = " + ".join(f"hh46S6C{t}_{j} R" + ("" if j == 0 else f" * {pw('d', j)}") for j in range(nd + 1))
    unf = " ".join(f"hh46S6C{t}_{j}" for j in range(nd + 1))
    steps = []
    for k in range(nd + 1):
        comb_s = " + ".join(" * ".join(x for x in [None if comb(nd - j, k - j) == 1 else str(comb(nd - j, k - j)),
                                                   f"hh46S6C{t}_{j} R", pw('(1 / 19)', j)] if x)
                            for j in range(k + 1))
        unfk = " ".join(f"hh46S6C{t}_{j}" for j in range(k + 1))
        steps.append(f"  · have e : {comb_s} = hh46S6E{t}_{k} (R - 1 / 3) := by\n      unfold hh46S6E{t}_{k} {unfk}; ring\n"
                     f"    rw [e]; exact hh46_s6_E{t}_pos_{k} (by linarith) (by linarith)")
    out.append(f"""/-- **Positivity of the expansion at `e = {e}`** on `[1/3, 7/19] × [0, 1/19]`. -/
theorem hh46_s6_pos{t} {{R d : ℝ}} (hR0 : 1 / 3 ≤ R) (hR1 : R ≤ 7 / 19) (hd0 : 0 ≤ d) (hd1 : d ≤ 1 / 19) :
    0 < {lhs} := by
  refine hh46Bern0g{nd} hd0 hd1 (by norm_num) {' '.join('?_' for _ in range(nd + 1))}
""" + "\n".join(steps) + "\n")
    out.append("end SmoothedOctagon\n")
    return "\n".join(out)

if __name__ == "__main__":
    outdir = sys.argv[1]
    for e in (R_(13, 5), R_(3)):
        M, C, ny, nd = coeffs(e)
        print(e, M, ny, nd, sum(1 for j in range(nd+1) for i in range(ny+1) if C[j][i] != 0), file=sys.stderr)
        t = tag(e)
        open(f"{outdir}/S6Id{t}.lean", "w").write(emit_id(e, M, C, ny, nd))
        open(f"{outdir}/S6Pos{t}.lean", "w").write(emit_pos(e, M, C, ny, nd))
