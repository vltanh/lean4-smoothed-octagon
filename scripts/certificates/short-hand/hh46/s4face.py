"""Emit S4Face.lean: the four face inequalities from the certificates."""
import sympy as sp, sys
sys.path.insert(0, '.')
from s4gen import FACES, ubar_nd, lexpr, log_ub, xs, vs
from leanfmt import slit, lnum
from fractions import Fraction as Fr

def face_thm(face, which):
    f = FACES[face]; tag = f"{which}{face}"
    al = f['lal']; be = f['lbe']
    n_, d_ = ubar_nd(f['be'])
    NU = lexpr(n_); DU = lexpr(d_)
    DUf = sp.factor(d_)
    DUfs = str(DUf).replace('**', ' ^ ')
    y0 = f['y0']; kk = 1 / y0; LL = log_ub(y0)
    kq = Fr(kk.p, kk.q); Lq = Fr(LL.p, LL.q)
    w = (kq - 1) / (kq + 1)
    lo = "0" if f['w0'] == 0 else lnum(Fr(f['w0'].p, f['w0'].q))
    hi = lnum(Fr(f['w0'].p, f['w0'].q) + Fr(f['g'].p, f['g'].q))
    halpos = "by linarith" if face == 'A' else "by linarith"
    if face == 'A':
        h3block = f"    have h3 : {be} - 1 ≠ 0 := by nlinarith"
    else:
        h3block = ("    have hx0' : x ≠ 0 := hx0.ne'\n"
                   "    generalize hb : (20 / 19 * x - 1) = b\n"
                   "    have h3 : b ≠ 0 := by rw [← hb]; linarith")
    substline = '    subst hb\n' if face == 'B' else ''
    return f"""/-- **`{which}` on face {face}** (surrogate certificate `hh46_s4_pos{tag}`). -/
theorem hh46_s4_face{tag} {{x v : ℝ}} (hx : 2 ≤ x) (hx2 : x ≤ 13 / 6) (hv : {lo} ≤ v) (hv2 : v ≤ {hi}) :
    1829 / 10000 < hh46S4{which}C x {be} {al} (hsUbar x {be}) := by
  have hx0 : 0 < x := by linarith
  have hal : 0 < {al} := {halpos}
  have hbe : 0 < {be} := by positivity
  have hdu : 0 < {DU} := by
    have e : {DU} = {DUfs} := by ring
    rw [e]
    have : 0 < {'v * x + x - 1' if face == 'A' else '20 * x - 19'} := by nlinarith
    positivity
  have hu : hsUbar x {be} = {NU} / {DU} := by
    rw [eq_div_iff hdu.ne']
    unfold hsUbar
    have h1 : x + 1 ≠ 0 := by positivity
    have h2 : 35 * x + 13 ≠ 0 := by positivity
{h3block}
    field_simp
{substline}    ring
  rw [hu]
  have hk : (0 : ℝ) < {slit(kq)} := by norm_num
  have hL : Real.log (1 / {slit(kq)}) ≤ {slit(Lq)} := by
    have h := hh46_log_ge_quintic (z := {slit(kq)}) (by norm_num)
    rw [one_div, Real.log_inv]
    norm_num at h ⊢
    linarith
  have h1 := hh46_s4_{which.lower()}R_le (u := {NU} / {DU}) hk hL hx0 hal hbe
  have h2 := hh46_s4_{which.lower()}R_link (k := {slit(kq)}) (L0 := {slit(Lq)}) (nu := {NU}) hx0 hal hbe hdu
  rw [hh46_s4_id{tag} x v] at h2
  have h4 := hh46_s4_pos{tag} hx hx2 hv hv2
  have hM := hh46_s4_M_pos (X := x) (AL := {al}) (A := {al} + {be}) (Sg := x * (x + 2) + {al} ^ 2)
    hx0 hal (by positivity) (by positivity) hdu
  have h5 := div_pos h4 hM
  rw [← h2] at h5
  linarith
"""

HEAD = """module

public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S4PosPhiA
public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S4PosPsiA
public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S4PosPhiB
public import SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.S4PosPsiB

/-!
# Heavy leaf `hs4_floor_box`: the floor on the two faces

Face A (`η = 13/5`: `α = 1 + 13δ/5`, `β = x(1 + δ)`, `0 ≤ δ ≤ 1/19`) and face B (`δ = 1/19`:
`β = 20x/19`, `108/95 ≤ α ≤ 22/19`), with `u = ū(x, β)`: `Φ, Ψ > 1829/10000`. The logarithm is
replaced by the surrogate `hh46S4Ls` around the minimizing corners (`y₀ = 2524608/3353029` on face A,
`y₀ = 103488/134749` on face B, inventory HS-S4 R22), and the cleared surrogates are positive by the
Bernstein certificates (generated by `scripts/certificates/short-hand/hh46/s4face.py`).

## Main API

`hh46_s4_facePhiA`, `hh46_s4_facePsiA`, `hh46_s4_facePhiB`, `hh46_s4_facePsiB`.
-/

@[expose] public section

namespace SmoothedOctagon
"""
if __name__ == "__main__":
    out = [HEAD]
    for face in ('A', 'B'):
        for which in ('Phi', 'Psi'):
            out.append(face_thm(face, which))
    out.append("end SmoothedOctagon\n")
    open(sys.argv[1], "w").write("\n".join(out))
