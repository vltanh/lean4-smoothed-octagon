"""Shared paths and module writer for the S2 heavy-leaf generators."""
import os, re
import sympy as sp

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, '..', '..', '..', '..', 'SmoothedOctagon', 'Exclusion', 'Mixed',
                                    'ShortHand', 'Heavy'))
MOD = 'SmoothedOctagon.Exclusion.Mixed.ShortHand.Heavy.'

def lean_expr(e):
    """sympy expression -> Lean string with `^ (n : ℕ)` exponents."""
    s = sp.sstr(e).replace('**', '^')
    return re.sub(r'\^(\d+)', r' ^ (\1 : ℕ)', s)

HDR = '''module

{imports}

/-!
# S2 heavy face signs: {title}

{doc}

(Generated by `scripts/certificates/short-hand/hh2/{gen}`; every identity is checked by
`ring`/`linear_combination`.)

## Main API

{api}
-/

@[expose] public section

namespace SmoothedOctagon

'''

def write(fn, imports, title, doc, api, body, gen):
    txt = HDR.format(imports="\n".join(f"public import {m}" for m in imports), title=title, doc=doc,
                     api=api, gen=gen) + body + "\nend SmoothedOctagon\n"
    with open(os.path.join(OUT, fn), 'w') as f:
        f.write(txt)
    print(fn, len(txt))
    return txt
