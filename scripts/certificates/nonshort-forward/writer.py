import pickle, sys, glob, os
from gen4 import lemma0g, lemmaI, lemma_pos
from gen5 import lemma_tr
from mk5 import DOC, LEAN, OUT, TITLE
def write_bern(jobs):
    needI = set(); need0g = set(); needTr = set()
    for X in jobs:
        G = pickle.load(open(f'{X}.gen.pkl','rb'))
        needI |= G['needI']; need0g |= G['need0g']; needTr.add((G['kind'], G['ny']))
    s = """module

public import SmoothedOctagon.Exclusion.Mixed.Nonshort.Bernstein
public import Mathlib.Tactic.FieldSimp

/-!
# Case M2, forward successor: Bernstein positivity with abstract coefficients

* `nsfBern0g n`: a polynomial `∑ cᵢ yⁱ` of degree `n` is positive on `[0, g]` (`g > 0`) when its
  Bernstein coefficients `∑_{i ≤ k} C(n - i, k - i) cᵢ gⁱ` are positive;
* `nsfBernI n_lo_hi`: the same on a numeric interval `[lo, hi]` (the coefficients are explicit
  rational linear forms in the `cᵢ`).

The coefficients are abstract, so the nested certificates of the `*Signs` modules apply these lemmas
with polynomial coefficients without expanding them (generated by
`scripts/certificates/m2-forward/gen5.py`; each identity is checked by `ring`).
-/

@[expose] public section

namespace SmoothedOctagon

""" + "\n".join(lemma_pos(n) for n in sorted(need0g | {n for (n, _, _) in needI})) + "\n" + "\n".join(lemma0g(n) for n in sorted(need0g)) + "\n" + "\n".join(lemmaI(n, lo, hi) for (n, lo, hi) in sorted(needI)) + "\n" + "\n".join(lemma_tr(k, n) for (k, n) in sorted(needTr)) + "\nend SmoothedOctagon\n"
    open(LEAN + 'Bernstein.lean', 'w').write(s)
def write_cert(X):
    G = pickle.load(open(f'{X}.gen.pkl','rb'))
    s = f"""module

public import SmoothedOctagon.Exclusion.Mixed.Nonshort.Forward.Bernstein

/-!
# Case M2, forward successor: {TITLE[X]}

Positivity of {DOC[X]}, written as `∑ᵢ cᵢ(h, s) Mᵢ zⁱ` with `cᵢ = ∑ₗ {X}Dᵢ_ₗ(h) sˡ` (the
multipliers `Mᵢ` encode the event-factor interval). Nested Bernstein certificate (generated by
`scripts/certificates/m2-forward/gen5.py`; every identity is checked by `ring`/`linear_combination`).

## Main API

* `{X}D*`: the coefficient polynomials; `{X}_pos`: the sign.
-/

@[expose] public section

namespace SmoothedOctagon

""" + "\n".join(G['code']) + "\nend SmoothedOctagon\n"
    open(LEAN + OUT[X], 'w').write(s)
    return len(s)
if __name__ == '__main__':
    jobs = sys.argv[1].split(',')
    write_bern(jobs)
    for X in sys.argv[2].split(',') if len(sys.argv) > 2 else jobs:
        print(X, write_cert(X))
