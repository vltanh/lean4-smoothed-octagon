"""Emit a Lean port of selected SmallerShort residuals with denotation lemmas
`X.denote ρ = (PS ρ).X`, PS ρ = ⟨ρ 0, …, ρ 5⟩."""
import sys
import expr, smaller
from expr import _nodes, children

VARS = ['r', 'delta', 'al', 'rho', 'v', 'E']
UNFOLD_ALWAYS = ['Point.P10', 'Point.P11', 'Point.F01', 'Point.xi', 'Point.f6']

def port(want, prefix):
    expr.names.clear()
    allnames = {}
    orig = expr.name
    def name2(nm, e):
        allnames.setdefault(e.i, []).append(nm)
        return orig(nm, e)
    smaller.name = name2
    f, fn = smaller.build()
    smaller.name = orig
    roots = [f[fn.index(w)].i for w in want]
    for r, w in zip(roots, want):
        allnames.setdefault(r, []).append(w)
    order = expr.subdag(roots)
    defname = {}
    for i in order:
        if _nodes[i][0] in ('var', 'const'):
            continue
        if i in allnames:
            defname[i] = prefix + allnames[i][0]
    out = []
    base = ', '.join([f'PS_{v}' for v in VARS] + UNFOLD_ALWAYS)
    for i in order:
        if i not in defname:
            continue
        body = expr.lean_term(i, {k: v for k, v in defname.items() if k != i})
        out.append(f'/-- `{allnames[i][0]}` -/\ndef {defname[i]} : IExpr := {body}')
        kids = set()
        def collect(j):
            for c in children(_nodes[j]):
                if c in defname:
                    kids.add(c)
                else:
                    collect(c)
        collect(i)
        kidlems = ', '.join(f'{defname[c]}_den' for c in sorted(kids))
        for k, nm in enumerate(allnames[i]):
            ln = f'{defname[i]}_den' if k == 0 else f'{defname[i]}_den{k}'
            if k > 0:
                out.append(f'theorem {ln} (ρ : ℕ → ℝ) : {defname[i]}.denote ρ = (PS ρ).{nm} := by\n'
                           f'  rw [{defname[i]}_den]; simp [Point.{nm}]')
                continue
            simps = ', '.join(x for x in [defname[i], 'IExpr.denote', kidlems] if x)
            out.append(
                f'theorem {ln} (ρ : ℕ → ℝ) : {defname[i]}.denote ρ = (PS ρ).{nm} := by\n'
                f'  simp only [{simps}, logDivR_eq]\n'
                f'  simp only [Point.{nm}, {base}, mul_zero, zero_mul, add_zero, zero_add,\n'
                f'    sub_zero, div_one]\n'
                f'  all_goals push_cast\n'
                f'  all_goals ring_nf')
    return '\n\n'.join(out), [defname[r] for r in roots], [
        (f'{defname[r]}_den' if allnames[r][0] == w else f'{defname[r]}_den{allnames[r].index(w)}')
        for r, w in zip(roots, want)]

if __name__ == '__main__':
    want = sys.argv[1].split(','); prefix = sys.argv[2]
    text, rootdefs, lems = port(want, prefix)
    print(f'''module

public import SmoothedOctagon.Interval.Check
public import SmoothedOctagon.Certificates.SmallerShort

/-!
# Benchmark port: residuals {", ".join(want)} of `CertSmallerShort`

Generated by the Python port script. Each named intermediate `X` of
`SmoothedOctagon.Certificates.SmallerShort.Point` used by these residuals becomes an `IExpr`
definition `{prefix}X`, with the denotation lemma `{prefix}X_den : {prefix}X.denote ρ = (PS ρ).X`,
`PS ρ = ⟨ρ 0, …, ρ 5⟩` (coordinates `r, δ, α, ρ, v, E`).

## Main API

`PS`, `{prefix}fs` (the residual list), `{prefix}fs_allNonneg`.
-/

@[expose] public section

set_option linter.unusedSimpArgs false
set_option linter.unusedTactic false
set_option linter.unreachableTactic false

namespace SmoothedOctagon.Interval.Bench

open SmoothedOctagon.Certificates SmoothedOctagon.Certificates.SmallerShort

/-- The point with coordinates `(r, δ, α, ρ, v, E) = (ρ 0, …, ρ 5)`. -/
noncomputable def PS (ρ : ℕ → ℝ) : Point := ⟨ρ 0, ρ 1, ρ 2, ρ 3, ρ 4, ρ 5⟩
''')
    for k, v in enumerate(VARS):
        print(f'theorem PS_{v} (ρ : ℕ → ℝ) : (PS ρ).{v} = ρ {k} := rfl')
    print('\ntheorem logDivR_eq (q : ℝ) : logDivR q = logDiv q := rfl\n')
    print(text)
    print(f'\n/-- The ported residuals. -/\ndef {prefix}fs : List IExpr := [{", ".join(rootdefs)}]')
    hyps = ' → '.join(f'0 ≤ (PS ρ).{w}' for w in want)
    pat = ' | '.join('rfl' for _ in want)
    bullets = '\n'.join(f'  · rw [{l}]; exact h{k}' for k, l in enumerate(lems))
    print(f'''
/-- Nonnegative residuals give `AllNonneg`. -/
theorem {prefix}fs_allNonneg (ρ : ℕ → ℝ) : {hyps} → AllNonneg {prefix}fs ρ := by
  intro {" ".join(f"h{k}" for k in range(len(want)))} f hf
  simp only [{prefix}fs, List.mem_cons, List.not_mem_nil, or_false] at hf
  rcases hf with {pat}
{bullets}

end SmoothedOctagon.Interval.Bench''')
