"""Emit a chunked Lean certificate for a SmallerShort sub-box (all 28 residuals ported)."""
import sys, pickle, collections
import fx, expr, smaller, run_ss
from certemit import pycheck, lean_cert, lean_box, leaves, chunk

if __name__ == '__main__':
    cand = pickle.load(open(sys.argv[1], 'rb'))[int(sys.argv[2])]
    K = int(sys.argv[3]); prefix = sys.argv[4]; note = sys.argv[5] if len(sys.argv) > 5 else ''
    n, cnt, path, B0, cert = cand
    f, fn = smaller.build()
    fs = [x.i for x in f]
    assert pycheck(fs, B0, cert), 'python check failed'
    chunks = []
    top = chunk(cert, B0, K, chunks)
    box_txt = ', '.join(f'[{l / fx.U:.4f}, {h / fx.U:.4f}]' for l, h in B0)
    out = ['module', '', 'public import SmoothedOctagon.Interval.SmallerShort.Res', '',
           '/-!', f'# Benchmark certificate for `CertSmallerShort` ({n} leaves, {len(chunks)} chunks)', '',
           f'The sub-box `(r, δ, α, ρ, v, E) ∈ {box_txt}` of `B₀` (exact dyadic endpoints in',
           f'`{prefix}box`); leaves: {cnt.get("R", 0)} natural, {cnt.get("S", 0)} slope,',
           f'{cnt.get("L", 0)} LP-weight combinations. Generated by the Python search with the exact',
           'arithmetic of `SmoothedOctagon.Interval`; each chunk is checked by `decide +kernel` in its',
           f'own declaration, `{prefix}sub` combines them, `{prefix}sub_real` is the statement.']
    if note:
        out += ['', note]
    out += ['-/', '', '@[expose] public section', '', 'namespace SmoothedOctagon.Interval.SS', '']
    for k, (B, c) in enumerate(chunks):
        out.append(f'/-- Chunk {k} ({leaves(c)} leaves). -/')
        out.append(f'noncomputable def {prefix}box{k} : List Ival := {lean_box(B)}')
        out.append(f'/-- Certificate of chunk {k}. -/')
        out.append(f'noncomputable def {prefix}cert{k} : Cert := {lean_cert(c)}')
        out.append(f'/-- Chunk {k} is excluded. -/')
        out.append(f'theorem {prefix}chunk{k} : Excluded r_fs {prefix}box{k} :=')
        out.append(f'  excluded_of_check (c := {prefix}cert{k}) (by decide +kernel)')
        out.append('')
    out.append(f'/-- The sub-box. -/\nnoncomputable def {prefix}box : List Ival := {lean_box(B0)}')
    out.append(f'/-- The chunk boxes. -/\nnoncomputable def {prefix}done : List (List Ival) := [' + ', '.join(f'{prefix}box{k}' for k in range(len(chunks))) + ']')
    out.append(f'/-- The top of the tree. -/\nnoncomputable def {prefix}top : Cert := {lean_cert(top)}')
    out.append(f'/-- The whole sub-box is excluded. -/')
    out.append(f'theorem {prefix}sub : Excluded r_fs {prefix}box :=')
    out.append(f'  excluded_of_check_done (fs := r_fs) (done := {prefix}done) (c := {prefix}top)')
    out.append(f'    (by decide +kernel)')
    out.append('    ⟨' + ', '.join(f'{prefix}chunk{k}' for k in range(len(chunks))) + '⟩')
    hs = ' '.join(f'h{i}' for i in range(28))
    pat = ', '.join(f'h{i}' for i in range(28))
    out.append(f'''
/-- **Benchmark statement.** No point of the sub-box has all 28 residuals of `CertSmallerShort`
nonnegative. -/
theorem {prefix}sub_real (ρ : ℕ → ℝ) (hρ : InBox {prefix}box ρ) : ¬ (PS ρ).AllResidualsNonneg := by
  rintro ⟨{pat}⟩
  exact {prefix}sub ρ hρ (r_fs_allNonneg ρ {hs})''')
    out.append('\nend SmoothedOctagon.Interval.SS')
    print('\n'.join(out))
