def split_box(B, bit):
    j = prob.split_axis(B); lo, hi = B[j]; m = (lo + hi) >> 1
    B = list(B); B[j] = (lo, m) if bit == '0' else (m, hi)
    return j, B

from certemit import children_boxes, kids

def has_fail(c):
    if c[0] in ('split', 'cut'):
        a, b = kids(c)
        return has_fail(a) or has_fail(b)
    return c[0] == 'FAIL'

def build(certs, path, B):
    if path in certs:
        return certs[path]
    j, BL = split_box(B, '0'); _, BR = split_box(B, '1')
    return ('split', j, build(certs, path + '0', BL), build(certs, path + '1', BR))

def verify_unit(args):
    B, c = args
    bad = 0
    def walk(c, B):
        nonlocal bad
        if c[0] in ('split', 'cut'):
            BL, BR = children_boxes(c, B)
            a, b = kids(c)
            walk(a, BL); walk(b, BR); return
        if not pycheck(FS, B, c):
            bad += 1
    walk(c, B)
    return bad

def partition(c, B, units):
    if leaves(c) <= FILE_MAX or c[0] not in ('split', 'cut'):
        units.append((B, c)); return ('hole', len(units) - 1)
    BL, BR = children_boxes(c, B)
    a, b = kids(c)
    l = partition(a, BL, units); r = partition(b, BR, units)
    return ('split', c[1], l, r) if c[0] == 'split' else ('cut', c[1], c[2], l, r)

def emit_unit(k, B, c):
    pre = f'p{k:04d}_'
    chunks = []
    top = chunk(c, B, CHUNK, chunks)
    out = [f'/-! ### Part {k}: {leaves(c)} leaves in {len(chunks)} chunks -/', '']
    for i, (Bi, ci) in enumerate(chunks):
        out.append(f'/-- Box of chunk {i}. -/')
        out.append(f'noncomputable def {pre}b{i} : List Ival := {lean_box(Bi)}')
        out.append(f'/-- Certificate of chunk {i} ({leaves(ci)} leaves). -/')
        out.append(f'noncomputable def {pre}c{i} : Cert := {lean_cert(ci)}')
        out.append(f'theorem {pre}k{i} : Excluded r_fs {pre}b{i} :=')
        out.append(f'  excluded_of_check (c := {pre}c{i}) (by decide +kernel)')
        out.append('')
    out.append(f'/-- The part box. -/\nnoncomputable def {pre}box : List Ival := {lean_box(B)}')
    if len(chunks) == 1:
        out.append(f'/-- Part {k} is excluded. -/\ntheorem {pre}ok : Excluded r_fs {pre}box := {pre}k0')
    else:
        out.append(f'/-- The chunk boxes. -/\nnoncomputable def {pre}done : List (List Ival) := [' +
                   ', '.join(f'{pre}b{i}' for i in range(len(chunks))) + ']')
        out.append(f'/-- The top of the part. -/\nnoncomputable def {pre}top : Cert := {lean_cert(top)}')
        out.append(f'/-- Part {k} is excluded. -/\ntheorem {pre}ok : Excluded r_fs {pre}box :=')
        out.append(f'  excluded_of_check_done (fs := r_fs) (done := {pre}done) (c := {pre}top)')
        out.append(f'    (by decide +kernel)')
        out.append('    ⟨' + ', '.join(f'{pre}k{i}' for i in range(len(chunks))) + '⟩')
    out.append('')
    return '\n'.join(out)

def emit_file(fi, parts):
    """parts: list of (k, B, c)"""
    nl = sum(leaves(c) for _, _, c in parts)
    ks = [k for k, _, _ in parts]
    out = ['module', '', 'public import SmoothedOctagon.Interval.SmallerShort.Res', '',
           '/-!', f'# `CertSmallerShort`, certificate file {fi}', '',
           f'Parts {ks[0]}–{ks[-1]} of the subdivision of `B₀` ({nl} leaves). Generated by the Python',
           'search with the exact arithmetic of `SmoothedOctagon.Interval`; each chunk of at most',
           f'{CHUNK} leaves is checked by `decide +kernel` in its own declaration, and `pNNNN_ok` combines',
           'the chunks of part `NNNN` for its box `pNNNN_box`.', '-/', '',
           '@[expose] public section', '', 'namespace SmoothedOctagon.Interval.SS', '']
    for k, B, c in parts:
        out.append(emit_unit(k, B, c))
    out.append('end SmoothedOctagon.Interval.SS')
    open(os.path.join(OUT, 'SmallerShort', f'C{fi:03d}.lean'), 'w').write('\n'.join(out) + '\n')

