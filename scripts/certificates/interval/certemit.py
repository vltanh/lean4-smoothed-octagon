"""Emit a chunked Lean certificate for a sub-box, with residual indices remapped."""
import sys, pickle
import fx, expr, run

def remap(c, m):
    if c[0] == 'split':
        return ('split', c[1], remap(c[2], m), remap(c[3], m))
    if c[0] == 'R':
        return ('R', m[c[1]])
    if c[0] == 'S':
        return ('S', [(m[k], w) for k, w in c[1]])
    raise ValueError(c)

def leaves(c):
    return leaves(c[2]) + leaves(c[3]) if c[0] == 'split' else 1

def pycheck(fs, B, c):
    if c[0] == 'split':
        j = c[1]; lo, hi = B[j]; m = (lo + hi) >> 1
        BL = list(B); BL[j] = (lo, m); BR = list(B); BR[j] = (m, hi)
        return pycheck(fs, BL, c[2]) and pycheck(fs, BR, c[3])
    if c[0] == 'R':
        r = expr.evalR(B, fs[c[1]], {})
        return r is not None and r[1] < 0
    memo = {}
    acc = expr.s_const(fx.ZERO)
    for k, w in reversed(c[1]):
        s = expr.evalS(B, fs[k], memo)
        if s is None:
            return False
        acc = expr.s_add(expr.s_scale(w, s), acc)
    return expr.slope_hi(B, acc) < 0

def lean_cert(c):
    if c[0] == 'split':
        return f'(.split {c[1]} {lean_cert(c[2])} {lean_cert(c[3])})'
    if c[0] == 'R':
        return f'(.byR {c[1]})'
    if c[0] == 'hole':
        return f'(.hole {c[1]})'
    return '(.byS [' + ', '.join(f'({k}, {w})' for k, w in c[1]) + '])'

def lean_box(B):
    return '[' + ', '.join(f'⟨{lo}, {hi}⟩' for lo, hi in B) + ']'

def chunk(c, B, K, chunks):
    """Replace subtrees with <= K leaves by holes; returns top tree."""
    if leaves(c) <= K or c[0] != 'split':
        chunks.append((B, c))
        return ('hole', len(chunks) - 1)
    j = c[1]; lo, hi = B[j]; m = (lo + hi) >> 1
    BL = list(B); BL[j] = (lo, m); BR = list(B); BR[j] = (m, hi)
    return ('split', j, chunk(c[2], BL, K, chunks), chunk(c[3], BR, K, chunks))

if __name__ == '__main__':
    cand = pickle.load(open(sys.argv[1], 'rb'))[int(sys.argv[2])]
    K = int(sys.argv[3]); prefix = sys.argv[4]; maxchunks = int(sys.argv[5]) if len(sys.argv) > 5 else 10**9
    n, nr, ns, used, path, B0, cert = cand
    prob = run.make(1, False)
    want = ['g7', 'g9', 'g10']
    m = {prob.names.index(w): k for k, w in enumerate(want)}
    cert = remap(cert, m)
    import nonshort
    g, gn = nonshort.build(1)
    fs = [g[gn.index(w)].i for w in want]
    assert pycheck(fs, B0, cert), 'python check failed'
    chunks = []
    top = chunk(cert, B0, K, chunks)
    chunks = chunks[:maxchunks] if maxchunks < len(chunks) else chunks
    print(f'-- sub-box {[(l / fx.U, h / fx.U) for l, h in B0]}: {n} leaves, {len(chunks)} chunks', file=sys.stderr)
    out = ['module', '', 'public import SmoothedOctagon.Interval.Bench.FwdRes', '',
           '/-!', f'# Benchmark certificate ({n} leaves, {len(chunks)} chunks of at most {K} leaves)', '',
           'A sub-box of the chart-1 root box of `CertNonshortForwardLower`,',
           '`a ∈ [1/2, 0.675]`, `c ∈ [1.0667, 1.3]`, `eps ∈ [0.4990, 0.9668]`, `ell ∈ [1/4, 1/2]`',
           '(exact dyadic endpoints in `fwc_box`), excluded by the slope enclosures of `g₇ = -phi`,',
           '`g₉ = turn` and `g₁₀ = v - Fend` alone (585 `g₁₀`, 368 `g₇`, 341 `g₉` leaves).',
           'Generated by the Python search with the exact arithmetic of `SmoothedOctagon.Interval`.',
           'Each chunk is checked by `decide +kernel` in its own declaration (bounded kernel memory);',
           f'`{prefix}sub` combines them through `hole` leaves, and `{prefix}sub_real` is the statement.',
           '',
           'Measured (one Lean process, Lean v4.36.0-rc2): 78 s of kernel checking for the 1294 leaves',
           '(60 ms per leaf; by regression 137 ms per `g₇` leaf, 41 ms per `g₁₀`, 9 ms per `g₉`),',
           '81 s wall for the file, 2.19 GB peak memory (1.6 GB of it is the Mathlib environment).',
           '-/', '',
           '@[expose] public section', '',
           'namespace SmoothedOctagon.Interval.Bench', '']
    for k, (B, c) in enumerate(chunks):
        out.append(f'/-- Chunk {k} ({leaves(c)} leaves). -/')
        out.append(f'noncomputable def {prefix}box{k} : List Ival := {lean_box(B)}')
        out.append(f'/-- Certificate of chunk {k}. -/')
        out.append(f'noncomputable def {prefix}cert{k} : Cert := {lean_cert(c)}')
        out.append(f'/-- Chunk {k} is excluded. -/')
        out.append(f'theorem {prefix}chunk{k} : Excluded fw1_fs {prefix}box{k} :=')
        out.append(f'  excluded_of_check (c := {prefix}cert{k}) (by decide +kernel)')
        out.append('')
    if maxchunks >= 10**9:
        out.append(f'/-- The sub-box. -/\nnoncomputable def {prefix}box : List Ival := {lean_box(B0)}')
        out.append(f'/-- The chunk boxes. -/\nnoncomputable def {prefix}done : List (List Ival) := [' + ', '.join(f'{prefix}box{k}' for k in range(len(chunks))) + ']')
        out.append(f'/-- The top of the tree. -/\nnoncomputable def {prefix}top : Cert := {lean_cert(top)}')
        out.append(f'/-- The whole sub-box is excluded. -/')
        out.append(f'theorem {prefix}sub : Excluded fw1_fs {prefix}box :=')
        out.append(f'  excluded_of_check_done (fs := fw1_fs) (done := {prefix}done) (c := {prefix}top)')
        out.append(f'    (by decide +kernel)')
        out.append('    ⟨' + ', '.join(f'{prefix}chunk{k}' for k in range(len(chunks))) + '⟩')
        out.append(f'''
/-- **Benchmark statement.** On the sub-box, no chart-1 point of `CertNonshortForwardLower` has
`g₇, g₉, g₁₀ ≥ 0`. -/
theorem {prefix}sub_real (ρ : ℕ → ℝ) (hρ : InBox {prefix}box ρ) :
    ¬ (0 ≤ (P ρ).g7 ∧ 0 ≤ (P ρ).g9 ∧ 0 ≤ (P ρ).g10) := fun ⟨h0, h1, h2⟩ =>
  {prefix}sub ρ hρ (fw1_fs_allNonneg ρ h0 h1 h2)''')
    out.append('\nend SmoothedOctagon.Interval.Bench')
    print('\n'.join(out))
