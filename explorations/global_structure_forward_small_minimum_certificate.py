def run():
    count = 0

    def check(condition, label):
        nonlocal count
        assert condition, label
        count += 1

    def zero(expr, label):
        check(S.cancel(expr) == 0, label)

    v = S.symbols("v", positive=True)
    w = (v-1)/(v+1)
    lower = 2*w + S.Rational(2, 3)*w**3
    upper = 2*w + S.Rational(2, 3)*w**3/(1-w*w)
    zero(1/v-S.diff(lower,v)-(v-1)**4/(v*(v+1)**4), "lower log bound derivative")
    zero(S.diff(upper,v)-1/v-(v-1)**4/(6*v*v*(v+1)**2), "upper log bound derivative")
    zero(lower.subs(v,1), "lower log base")
    zero(upper.subs(v,1), "upper log base")

    u,z,h,Lq,Lh,LH = S.symbols("u z h Lq Lh LH", positive=True)
    t=1/(1+z)
    x=z/(1+z)
    q=(1+z)**2/(1+u)
    H=(1+z)**2/(z*z+u)
    A=2-t-2*t*t+t**3*q-t*Lq
    B=h/H+t-x*x*H/h-x*x+x**3*H-x*Lh
    alpha=H*(h-x)/(t*q)
    M1=H*(1-t*q)*(h-1)/(t*q)
    M2=H*(t*(q-1)+(h-1)*(q-t))/(t*q*q)
    Fh=1+x*x*h-x*h*Lh/(h-1)
    FH=1+x*x*H-x*H*LH/(H-1)
    E=alpha*A-B-M1*Fh-M2*FH
    zero(S.diff(E,Lq)+H*(h-x)/q, "negative log-q coefficient")
    zero(S.diff(E,Lh)-x-H*(1-t*q)*x*h/(t*q), "positive log-h coefficient")
    zero(S.diff(E,LH)-M2*x*H/(H-1), "positive log-H coefficient")
    zero(1-t*q-(u-z)/(1+u), "strict-star multiplier sign")

    # Independent physical normalization of each residual component.
    a,b=S.symbols("a b", positive=True)
    s,K,Kb=a+b,a*a+4,b*b+4
    qp,Hp=s*s/K,s*s/Kb
    Ap=(a+2*b-2*a*a/s+a**3/K-a*Lq)/s
    Bp=(Kb*h/s+a-b*b*s/(Kb*h)-b*b/s+b**3/Kb-b*Lh)/s
    alphap=K*(h*s-b)/(a*Kb)
    m1p=s*(4-a*b)*(h-1)/(a*Kb)
    m2p=K*K*(a*(qp-1)+(h-1)*(s*qp-a))/(a*s*s*Kb)
    for abstract,physical,label in [
        (q,qp,"q normalization"),(H,Hp,"H normalization"),
        (A,Ap,"central cost derivative"),(B,Bp,"outer cost derivative"),
        (alpha,alphap,"stationarity coefficient"),
        (M1,m1p,"first norm coefficient"),(M2,m2p,"second norm coefficient"),
    ]:
        zero(abstract.subs({u:4/a**2,z:b/a})-physical,label)

    rational_upper=S.cancel(E.subs({Lq:lower.subs(v,q),Lh:upper.subs(v,h),LH:upper.subs(v,H)}))
    denominator=6*h*(h+1)*(u+z*z)**2*(z+1)**3*(u+z*z+2*z+2)**3*(u+2*z*z+2*z+1)
    numerator=S.Poly(S.cancel(denominator*rational_upper),u,z,h)
    check(numerator.degree_list()==(7,15,4),"fixed rational numerator degrees")

    Y,R,T=S.symbols("Y R T", nonnegative=True)
    hn=(1+z)**2*z+T*(1+z)*(z*z+u)
    hd=z*(z*z+u)*(1+T)
    hnew=hn/hd
    zero(hnew-(H+T*(1+z)/z)/(1+T),"h interpolation")
    zero((hnew-H)/((1+z)/z-hnew)-T,"h coordinate inverse")
    hp=S.Poly(numerator.as_expr(),h)
    Nh=S.Poly(sum(co*hn**powers[0]*hd**(4-powers[0]) for powers,co in hp.terms()),z,u,T)
    check(Nh.degree(z)==25,"fixed h-cleared z degree")

    zn=2+Y+(6+2*Y)*R
    zd=2*(1+R)
    znew=zn/zd
    unew=3+Y
    zero(unew-znew-(Y+4)/(2*(1+R)),"star coordinate")
    zero(2*znew+1-unew-(Y+4)*R/(1+R),"hard-face coordinate")
    zero((2*znew+1-unew)/(2*(unew-znew))-R,"state coordinate inverse")

    up=[S.Poly((3+Y)**i,Y,R,T) for i in range(Nh.degree(u)+1)]
    zp=[S.Poly(zn**i,Y,R,T) for i in range(26)]
    dp=[S.Poly(zd**i,Y,R,T) for i in range(26)]
    tp=[S.Poly(T**i,Y,R,T) for i in range(5)]
    cleared=S.Poly(0,Y,R,T)
    for (i,j,k),co in Nh.terms():
        cleared+=co*zp[i]*up[j]*dp[25-i]*tp[k]

    Q=[]
    expected_counts=[122,187,178,170,135]
    for j,rows in enumerate(TABLES):
        expression=0
        for n,(factor,coefficients) in enumerate(rows):
            check(factor>0 and all(c>=0 for c in coefficients),f"positive table {j} row {n}")
            check(reduce(gcd,coefficients)==1,f"reduced table {j} row {n}")
            expression+=factor*R**n*sum(c*Y**i for i,c in enumerate(coefficients))
        Q.append(S.Poly(expression,Y,R,T))
        check(len(Q[-1].terms())==expected_counts[j],f"fixed table {j} coefficient count")

    AA=S.Poly(2*R*Y+6*R+Y+2,Y,R,T)
    BB=S.Poly(4*R*R*Y+12*R*R+4*R*Y+12*R+Y+4,Y,R,T)
    CC=S.Poly(4*R*R*Y+14*R*R+4*R*Y+14*R+Y+4,Y,R,T)
    rhs=(AA**4*BB*CC*Q[0]+tp[1]*AA**3*BB*Q[1]
         +tp[2]*AA**2*BB**2*Q[2]+tp[3]*AA*BB**3*Q[3]+tp[4]*AA*BB**4*Q[4])
    rhs*=S.Poly(8*(2*R+1)**2*(Y+4)**12,Y,R,T)
    check(cleared+rhs==S.Poly(0,Y,R,T),"full displayed polynomial identity")
    check(Q[0].coeff_monomial(R**3)==1966080,"strict coefficient at Y=T=0")
    print(f"{count} exact identities/sign checks passed (SymPy {S.__version__}).")


if __name__=="__main__":
    run()
